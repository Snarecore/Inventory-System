// Helper to filter mock transactions by date range
export const filterMockSalesByDateRange = (
  items: MockSaleItem[],
  startDate: string,
  endDate: string
): MockSaleItem[] => {
  if (!startDate || !endDate) return items;
  const start = moment(startDate).startOf("day");
  const end = moment(endDate).endOf("day");

  return items.filter((item) => {
    const dStr = item.salesDate || item.saleDate || item.date;
    if (!dStr) return true;
    const d = moment(dStr);
    return d.isBetween(start, end, undefined, "[]");
  });
};
